// ED-003 section 5.8 item 6 (step C4): a link inserted from the dialog and Ctrl+clicked; the
// download passing the oracle with only the main part and the relationships changed.
import { test, expect } from '@playwright/test';
import { openFixture, download, fixture, comparePackages, selectBlock, caretInBlock } from './helpers.js';

const body = '.docx-editor .ProseMirror[aria-label="Document"]';

test('a link inserted over a selection from the dialog, shown with its target, Ctrl+clicked into a new tab, then removed; the download carries the relationship', async ({ page, context }) => {
  await openFixture(page, 'tracked-changes.docx');
  await selectBlock(page, 4);   // "Some text."
  const button = page.getByTestId('link-button');
  await expect(button).not.toHaveClass(/pressed/);
  await button.click();
  await page.getByTestId('link-address').fill('https://docx4j.org/');
  await page.getByRole('button', { name: 'OK' }).click();
  const link = page.locator(`${body} > p`).nth(4).locator('a.link');
  await expect(link).toHaveText('Some text.');
  await expect(link).toHaveAttribute('data-target', 'https://docx4j.org/');
  await caretInBlock(page, 4, 2);
  await expect(button).toHaveClass(/pressed/);
  // Ctrl+click opens the address in a new tab; a plain click only places the caret. The address is
  // answered here: CI's runner cannot reach the site, and the tab showed Chromium's error page.
  await context.route('https://docx4j.org/**', (route) => route.fulfill({ contentType: 'text/html', body: '<title>docx4j</title>' }));
  const [opened] = await Promise.all([context.waitForEvent('page'), link.click({ modifiers: ['Control'] })]);
  await opened.waitForLoadState();
  expect(opened.url()).toBe('https://docx4j.org/');
  await opened.close();
  await link.click();
  expect(context.pages()).toHaveLength(1);
  // The download: the main part and the relationships part (regenerated by design) carry it.
  const saved = await download(page);
  expect(comparePackages(await fixture('tracked-changes.docx'), saved, ['word/document.xml', 'docProps/app.xml'])).toEqual([]);
  const { WordprocessingMLPackage } = await import('@docx4j/core-ts');
  const pkg = await WordprocessingMLPackage.load(saved);
  const xml = await pkg.getMainDocumentPart().getXml();
  const id = /<w:hyperlink [^>]*r:id="(rId\d+)"/.exec(xml)?.[1];
  expect(id).toBeTruthy();
  expect(pkg.getMainDocumentPart().relationshipsPart!.getRelationshipById(id!)?.target).toBe('https://docx4j.org/');
  // Remove from the dialog: the text stays.
  await caretInBlock(page, 4, 2);
  await page.keyboard.press('Control+k');
  await expect(page.getByTestId('link-address')).toHaveValue('https://docx4j.org/');
  await page.getByTestId('link-remove').click();
  await expect(page.locator(`${body} > p`).nth(4).locator('a.link')).toHaveCount(0);
  await expect(page.locator(`${body} > p`).nth(4)).toHaveText('Some text.');
});

test('a link to a bookmark: the place list offers the document\'s bookmarks, and Ctrl+click puts the caret there', async ({ page }) => {
  await openFixture(page, 'loadAndSave.docx');
  await caretInBlock(page, 0);
  await page.keyboard.press('Control+k');
  const places = page.getByTestId('link-bookmark');
  await expect(places.locator('option', { hasText: '_Toc230018411' })).toHaveCount(1);
  await places.selectOption('_Toc230018411');
  await page.getByTestId('link-text').fill('to section 3');
  await page.getByRole('button', { name: 'OK' }).click();
  const link = page.locator(`${body} a.link`, { hasText: 'to section 3' });
  await expect(link).toHaveAttribute('data-target', '#_Toc230018411');
  await link.click({ modifiers: ['Control'] });
  const at = await page.evaluate(() => (window as unknown as { docx4jEditor: { state: { selection: { from: number } } } }).docx4jEditor.state.selection.from);
  expect(at).toBeGreaterThan(20);
  // The caret sits where the bookmark starts: in a paragraph that is not the first.
  const block = await page.evaluate(() => { const v = (window as unknown as { docx4jEditor: { state: { doc: { resolve(p: number): { index(d: number): number } }; selection: { from: number } } } }).docx4jEditor; return v.state.doc.resolve(v.state.selection.from).index(0); });
  expect(block).toBeGreaterThan(0);
  // The jump puts the target's paragraph at the top of the page area, its content below it (ED-005 section 12.94),
  // unless the area cannot scroll that far.
  const placed = await page.evaluate(() => {
    const area = document.querySelector('.page-area')!;
    const sel = document.getSelection()!;
    const node = sel.focusNode!;
    const p = (node.nodeType === 3 ? node.parentElement! : (node as Element)).closest('p')!;
    const top = p.getBoundingClientRect().top - area.getBoundingClientRect().top;
    const atEnd = area.scrollTop + area.clientHeight >= area.scrollHeight - 1;
    return { top, atEnd, scrolled: area.scrollTop };
  });
  expect(placed.scrolled).toBeGreaterThan(0);
  if (!placed.atEnd) expect(placed.top).toBeLessThan(40);
});

test('a new link takes Word\'s look at once: the Hyperlink style, added to a document that lacks it, colours and underlines it (core-ts 0.2.1, CR-002 section 25)', async ({ page }) => {
  await openFixture(page, 'sections-multiple.docx');
  const index = await page.evaluate(() => {
    const doc = (window as unknown as { docx4jEditor: { state: { doc: { childCount: number; child(i: number): { textContent: string } } } } }).docx4jEditor.state.doc;
    for (let k = 0; k < doc.childCount; k++) if (doc.child(k).textContent === 'This is a test.') return k;
    return -1;
  });
  expect(index).toBeGreaterThanOrEqual(0);
  const paragraph = page.locator(`${body} > p`).nth(index);
  /** The colour of the element holding the text, and whether it or an ancestor up to the paragraph is underlined. */
  const look = (): Promise<{ color: string; underlined: boolean }> => paragraph.evaluate((p) => {
    const walker = document.createTreeWalker(p, NodeFilter.SHOW_TEXT);
    let el = (walker.nextNode() as Text).parentElement!;
    const color = getComputedStyle(el).color;
    let underlined = false;
    for (; el && el !== p.parentElement; el = el.parentElement!) if (getComputedStyle(el).textDecorationLine.includes('underline')) underlined = true;
    return { color, underlined };
  });
  const before = await look();
  expect(before.underlined).toBe(false);
  await selectBlock(page, index);
  await page.getByTestId('link-button').click();
  await page.getByTestId('link-address').fill('https://docx4j.org/');
  await page.getByRole('button', { name: 'OK' }).click();
  // The paragraph's leading atoms are linked too, so the link is drawn in more than one element.
  await expect(paragraph.locator('a.link', { hasText: 'This is a test.' })).toHaveCount(1);
  const after = await look();
  expect(after.underlined).toBe(true);
  expect(after.color).not.toBe(before.color);
});
